"""Pre-draw the timelines so the page appears instantly.

1. Solve every storyline layout (a few hundred ms each) and store it in
   timelines/layout-cache.js, so the browser never has to.
2. Render every timeline (desktop and mobile) and write the finished SVG, legends, tabs and
   titles into index.html between the <!--BAKE:...--> markers. The browser paints those
   straight from the HTML; the script then swaps in identical, interactive copies.

Re-run after editing any timeline or the renderer:

    pip install playwright && playwright install chromium
    python3 bake.py

If the data changes and you forget, the page still works: it notices the signature mismatch
and runs the solver in the browser.
"""
import asyncio, json, pathlib, re
from playwright.async_api import async_playwright

ROOT = pathlib.Path(__file__).parent
OUT = ROOT / "timelines" / "layout-cache.js"

async def page(pw, width, js, fresh=True):
    b = await pw.chromium.launch()
    pg = await b.new_page(viewport={"width": width, "height": 900})
    # ignore the existing cache so every layout is solved fresh
    if fresh:
        await pg.route("**/layout-cache.js", lambda r: r.fulfill(body="window.LAYOUT_CACHE = {};", content_type="text/javascript"))
    await pg.add_init_script("window.BAKING = true")
    await pg.goto((ROOT / "index.html").resolve().as_uri())
    out = await pg.evaluate(js)
    await b.close()
    return out

# build() annotates the timeline data as it renders, so each layout is solved on a fresh page
SOLVE = """id => { const s = document.createElementNS(SVGNS, 'svg'), l = document.createElement('div');
  const W = build(id, s, l, %s); return [W, LAYOUT_OUT]; }"""

async def run(pw, width):
    ids = await page(pw, width, "TL_ORDER")
    cache, natural, minW = {}, {}, await page(pw, width, "MIN_W")
    for tl in ids:
        natural[tl] = round((await page(pw, width, f"({SOLVE % 0})('{tl}')"))[0])
        cache.update((await page(pw, width, f"({SOLVE % 'MIN_W'})('{tl}')"))[1])
    return {"cache": cache, "natural": natural, "minW": minW}

RENDER = """id => {
  const svg = document.createElementNS(SVGNS, 'svg'), lg = document.createElement('div');
  document.body.append(svg, lg);
  build(id, svg, lg, MIN_W);
  if (!LAYOUT_OUT[Object.keys(LAYOUT_OUT)[0]] || !Object.values(LAYOUT_OUT).every(Boolean)) throw 'no layout';
  return { svg: svg.outerHTML, legend: lg.innerHTML, title: TIMELINES[id].title, tab: TIMELINES[id].tab, span: TIMELINES[id].span };
}"""

def esc(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

async def main():
    async with async_playwright() as pw:
        d = await run(pw, 1300)
        m = await run(pw, 390)
        too_wide = {k: v for k, v in d["natural"].items() if v > d["minW"]}
        if too_wide:
            print(f"warning: wider than MIN_W={d['minW']}: {too_wide}; raise MIN_W and the CSS width in index.html")
        cache = {**d["cache"], **m["cache"]}
        OUT.write_text("// generated by bake.py, do not edit\nwindow.LAYOUT_CACHE = " + json.dumps(cache, separators=(",", ":")) + ";\n")
        print("natural widths", d["natural"], "->", OUT, f"{OUT.stat().st_size // 1024} KB")

        # 2. render with the new cache and bake the markup into index.html
        ids = await page(pw, 1300, "TL_ORDER")
        out = {"d": {}, "m": {}}
        for v, width in (("d", 1300), ("m", 390)):
            for tl in ids:
                out[v][tl] = await page(pw, width, f"({RENDER})('{tl}')", fresh=False)
                assert "crossings" not in out[v][tl]["svg"]

    def svg_tag(v, tl):
        s = out[v][tl]["svg"]
        return s.replace("<svg ", f'<svg class="baked" data-tl="{tl}" data-v="{v}" ', 1)

    blocks = {
        "tabs": "".join(f'<a href="#{tl}" data-tl="{tl}">{esc(out["d"][tl]["tab"])} <span>{esc(out["d"][tl]["span"])}</span></a>' for tl in ids),
        "title": "".join(f'<span class="baked" data-tl="{tl}">{esc(out["d"][tl]["title"])}</span>' for tl in ids),
        "legends": "".join(f'<div class="legend baked" data-tl="{tl}">{out["d"][tl]["legend"]}</div>' for tl in ids),
        "charts": "".join(svg_tag(v, tl) for v in ("d", "m") for tl in ids),
    }
    css = []
    for tl in ids:
        sel = f'html[data-tl="{tl}"]' if tl != ids[0] else f':is(html[data-tl="{tl}"], html:not([data-tl]))'
        css.append(f'{sel} #title .baked[data-tl="{tl}"] {{ display: inline; }}')
        css.append(f'{sel} #legends .baked[data-tl="{tl}"] {{ display: flex; }}')
        css.append(f'{sel} #tabs a[data-tl="{tl}"] {{ color: var(--bg); background: var(--fg); }}')
        css.append(f'@media (min-width: 760px) {{ {sel} #charts .baked[data-tl="{tl}"][data-v="d"] {{ display: block; }} }}')
        css.append(f'@media (max-width: 759.98px) {{ {sel} #charts .baked[data-tl="{tl}"][data-v="m"] {{ display: block; }} }}')

    html = (ROOT / "index.html").read_text()
    for k, v in blocks.items():
        html = re.sub(rf"<!--BAKE:{k}-->.*?<!--/BAKE-->", lambda _: f"<!--BAKE:{k}-->{v}<!--/BAKE-->", html, flags=re.S)
    html = re.sub(r'<style id="baked-css">.*?</style>', lambda _: '<style id="baked-css">\n' + "\n".join(css) + "\n</style>", html, flags=re.S)
    (ROOT / "index.html").write_text(html)
    print("baked markup into index.html,", len(html) // 1024, "KB")

asyncio.run(main())
